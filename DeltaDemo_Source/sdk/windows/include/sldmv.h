/*********************************************************************************************************************************************************************/
/**
* @brief 打开控制器（SLDM_Open升级函数，参数带完整ip地址）
* @param PC_IP_1：	 用户主机IP地址第1位，如：192
*		 PC_IP_2：   用户主机IP地址第2位，如：168
*		 PC_IP_3：   用户主机IP地址第3位，如：100
*		 PC_IP_4：   用户主机IP地址第4位，如：101
*		 Card_IP_4： 控制器IP地址第4位，如：1。控制器IP地址前3位必须与用户主机IP地址前3位相同
*        type：      以太网传输方式,取值范围：
*						0-UDP (默认)
*						1-SolidServer驱动通讯方式
* @return 成功返回0.
* @remark
*/
